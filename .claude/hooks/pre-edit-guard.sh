#!/usr/bin/env bash
# PreToolUse: 수정하면 안 되는 파일을 AI가 건드리기 전에 차단 (exit 2 = 차단, stderr가 AI에게 전달됨)
set -uo pipefail
INPUT="$(cat)"
command -v jq >/dev/null || { echo "jq 미설치: brew install jq (가드 비활성)" >&2; exit 0; }

FILE="$(echo "$INPUT" | jq -r '.tool_input.file_path // empty')"
[ -z "$FILE" ] && exit 0
ROOT="${CLAUDE_PROJECT_DIR:-$(pwd)}"
REL="${FILE#"$ROOT"/}"

# 1) 비밀값 파일
case "$REL" in
  .env|*/.env|*.pem|*id_rsa*)
    echo "차단: 비밀값 파일($REL)은 수정할 수 없습니다. .env.example 을 수정하세요." >&2
    exit 2 ;;
esac

# 2) 이미 커밋된 마이그레이션 수정 금지
case "$REL" in
  db/migrations/*)
    if [ -f "$FILE" ] && git -C "$ROOT" cat-file -e "HEAD:$REL" 2>/dev/null; then
      echo "차단: $REL 은 이미 커밋된 마이그레이션입니다. 'make migrate-new name=...' 으로 새 파일을 만드세요." >&2
      exit 2
    fi ;;
esac

# 3) sqlc 생성 코드 직접 수정 금지
case "$REL" in
  *.go)
    if [ -f "$FILE" ] && head -3 "$FILE" | grep -q "Code generated by sqlc"; then
      echo "차단: $REL 은 sqlc 생성 코드입니다. db/queries 의 SQL을 고치고 'make sqlc' 를 실행하세요." >&2
      exit 2
    fi ;;
esac

# 4) 하네스 자체를 AI가 몰래 약화시키지 않도록
case "$REL" in
  scripts/check-arch.sh|.claude/*|harness/*)
    echo "차단: 하네스 파일($REL)은 사람이 직접 수정합니다. 규칙 변경이 필요하면 이유를 설명하고 사용자에게 요청하세요." >&2
    exit 2 ;;
esac

exit 0
